@app.route("/api/predict", methods=["POST"])
def predict():
    """
    Main prediction endpoint.
    Accepts 8 student features via JSON and performs inference using the pre-trained pipeline.
    """
    if LOADED_MODEL is None:
        return jsonify({
            "status": "error",
            "message": "Model is not loaded. Please verify server initialization."
        }), 500

    payload = request.get_json(silent=True)
    if payload is None:
        # Fall back to form data if sent via multipart/x-www-form-urlencoded
        payload = request.form.to_dict()

    is_valid, error_msg, df_input, cleaned_summary = validate_and_parse_input(payload)
    if not is_valid:
        return jsonify({
            "status": "error",
            "message": error_msg
        }), 400

    try:
        # Perform inference using serialized pipeline directly
        pred_label = LOADED_MODEL.predict(df_input)[0]
        probs = LOADED_MODEL.predict_proba(df_input)[0]

        classes = list(LOADED_MODEL.classes_)
        eligible_idx = classes.index("Eligible")
        not_eligible_idx = classes.index("Not Eligible")

        p_eligible = round(float(probs[eligible_idx]) * 100.0, 2)
        p_not_eligible = round(float(probs[not_eligible_idx]) * 100.0, 2)
        confidence = round(float(max(probs)) * 100.0, 2)

        # Rationalizing high-confidence factors for transparency
        factors = []
        if cleaned_summary["FamilyIncome"] <= 200000:
            factors.append("Annual family income falls within priority means-tested threshold (<= Rs. 2,00,000).")
        elif cleaned_summary["FamilyIncome"] > 350000:
            factors.append("Annual family income exceeds typical affirmative means-tested ceilings.")

        if cleaned_summary["12thMarks"] >= 80.0:
            factors.append("Strong academic qualification (>= 80.0% board marks) bolsters merit-cum-means scoring.")
        elif cleaned_summary["12thMarks"] < 60.0:
            factors.append("12th board score is in the lower qualifying tier (< 60.0%).")

        if cleaned_summary["FirstGraduate"] == "Yes":
            factors.append("First-generation graduate status provides additional affirmative consideration.")

        if cleaned_summary["Community"] in ["SC", "ST"]:
            factors.append("Application benefits from statutory affirmative category allocations.")

        return jsonify({
            "status": "success",
            "prediction": str(pred_label),
            "is_eligible": bool(pred_label == "Eligible"),
            "eligible_probability": p_eligible,
            "not_eligible_probability": p_not_eligible,
            "confidence": confidence,
            "input_summary": cleaned_summary,
            "decision_factors": factors,
            "model_used": "Random Forest Classifier (100 Estimators)",
            "disclaimer": DISCLAIMER_TEXT
        })

    except Exception as e:
        logger.error(f"Inference error encountered: {str(e)}", exc_info=True)
        return jsonify({
            "status": "error",
            "message": "Internal error occurred while processing student attributes. Please check inputs and try again."
        }), 500


