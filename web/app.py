def load_model():
    """Load serialized scikit-learn pipeline once on startup."""
    global LOADED_MODEL, ACTIVE_MODEL_PATH
    if os.path.exists(PRIMARY_MODEL_PATH):
        target_path = PRIMARY_MODEL_PATH
    elif os.path.exists(FALLBACK_MODEL_PATH):
        target_path = FALLBACK_MODEL_PATH
    else:
        raise FileNotFoundError(
            f"Trained model artifact not found. Looked at '{PRIMARY_MODEL_PATH}' and '{FALLBACK_MODEL_PATH}'."
        )

    logger.info(f"Loading pre-trained pipeline from: {target_path}")
    LOADED_MODEL = joblib.load(target_path)
    ACTIVE_MODEL_PATH = target_path
    logger.info(f"Pipeline successfully loaded! Classes: {getattr(LOADED_MODEL, 'classes_', 'N/A')}")
    return LOADED_MODEL


